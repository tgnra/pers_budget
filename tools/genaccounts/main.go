// Command genaccounts reads accounts.txt ("username:password" per line, # comments)
// and writes accounts_gen.go containing PBKDF2 hashes of the passwords.
// It is run by `go generate` from the repository root.
package main

import (
	"bufio"
	"crypto/pbkdf2"
	"crypto/rand"
	"crypto/sha256"
	"encoding/base64"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"
)

const (
	iterations = 600_000
	in         = "accounts.txt"
	out        = "accounts_gen.go"
)

var validUser = regexp.MustCompile(`^[a-z0-9_-]{1,32}$`)

func hash(password string) string {
	salt := make([]byte, 16)
	rand.Read(salt)
	key, err := pbkdf2.Key(sha256.New, password, salt, iterations, 32)
	if err != nil {
		fail(err.Error())
	}
	enc := base64.RawStdEncoding
	return fmt.Sprintf("pbkdf2-sha256$%d$%s$%s", iterations, enc.EncodeToString(salt), enc.EncodeToString(key))
}

func fail(msg string) {
	fmt.Fprintln(os.Stderr, "genaccounts:", msg)
	os.Exit(1)
}

func main() {
	f, err := os.Open(in)
	if err != nil {
		fail(fmt.Sprintf("%v\ncreate %s from accounts.example.txt first", err, in))
	}
	defer f.Close()

	accounts := map[string]string{}
	sc := bufio.NewScanner(f)
	for n := 1; sc.Scan(); n++ {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		user, pass, ok := strings.Cut(line, ":")
		user = strings.TrimSpace(user)
		switch {
		case !ok || pass == "":
			fail(fmt.Sprintf("%s:%d: expected username:password", in, n))
		case !validUser.MatchString(user):
			fail(fmt.Sprintf("%s:%d: username must be 1-32 chars of a-z 0-9 _ -", in, n))
		case accounts[user] != "":
			fail(fmt.Sprintf("%s:%d: duplicate username %q", in, n, user))
		}
		accounts[user] = hash(pass)
	}
	if err := sc.Err(); err != nil {
		fail(err.Error())
	}
	if len(accounts) == 0 {
		fail("no accounts in " + in)
	}

	users := make([]string, 0, len(accounts))
	for u := range accounts {
		users = append(users, u)
	}
	sort.Strings(users)

	var b strings.Builder
	b.WriteString("// Code generated by tools/genaccounts from accounts.txt. DO NOT EDIT.\n\npackage main\n\n")
	b.WriteString("var accountHashes = map[string]string{\n")
	for _, u := range users {
		fmt.Fprintf(&b, "\t%q: %q,\n", u, accounts[u])
	}
	b.WriteString("}\n\n")
	dummy := make([]byte, 24)
	rand.Read(dummy)
	fmt.Fprintf(&b, "var dummyHash = %q\n", hash(base64.RawStdEncoding.EncodeToString(dummy)))

	if err := os.WriteFile(out, []byte(b.String()), 0o600); err != nil {
		fail(err.Error())
	}
	fmt.Printf("genaccounts: wrote %d account(s) to %s\n", len(users), out)
}
